function hashSeed(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

/** seed (thường là id lá bài): cùng 1 lá luôn ra cùng 1 tranh, ở mọi máy */
export function cardImage(type: CardType, seed?: string | number): string | undefined {
  const list = CARD_VARIANTS[type];
  if (!list?.length) return undefined;
  const file = seed === undefined ? list[0] : list[hashSeed(String(seed)) % list.length];
  return `/${encodeURIComponent(file)}`;
}
