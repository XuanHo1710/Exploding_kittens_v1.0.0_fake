function makeRealmGatekeepers(
  mapId: RealmMapId,
  tier: number,
  el: ElementType,
  weak: ElementType,
  specs: readonly { suffix: string; nameVi: string; arch: string; x: number; y: number }[],
): GatekeeperEncounter[] {
  return specs.map((s, idx) => {
    const scale = 1 + (tier - 1) * 0.42 + idx * 0.12;
    return {
      gkId: `${mapId}_gk_${s.suffix}`,
      mapId,
      nameVi: s.nameVi,
      archetype: s.arch,
      x: s.x,
      y: s.y,
      patrolWaypoints: [
        [s.x, s.y - 2],
        [s.x, s.y + 2],
      ],
      aggroRadius: 3,
      gateBarrierTiles: [
        [s.x + 1, s.y - 1],
        [s.x + 1, s.y],
        [s.x + 1, s.y + 1],
      ],
      enemies: [
        {
          enemyId: `${s.arch}_lead`,
          nameVi: s.nameVi,
          element: el,
          weakness: weak,
          maxHp: Math.round(620 * scale),
          atk: Math.round(58 * scale),
          def: Math.round(28 * scale),
          spd: Math.round(88 + tier * 4 + idx * 2),
          maxBreak: Math.round(90 + tier * 15),
          spriteKey: s.arch,
          cellSize: 192,
          rows: 4,
          attackNameVi: 'Gate Breaker Combo',
          hitBeatsMs: idx >= 1 ? [420, 740, 1060] : [450, 820],
          hitPowerMult: 1.15,
          aiStyle: GATEKEEPER_AI[s.arch] ?? 'brute',
        },
        // lính hộ vệ: chốt thứ 2 có 1 lính, chốt thứ 3 có 2 lính (quái nhỏ của vùng)
        ...REALM_MONSTER_POOLS[mapId]
          .slice(idx === 1 ? 0 : 1, idx === 1 ? 1 : idx >= 2 ? 3 : 0)
          .map((mid) => makeMonsterTemplate(mid, tier, { minion: true, scale: 0.9 })),
      ],
      firstClearAstralSeal: 160 + tier * 20,
      expReward: 120 * tier,
    };
  });
}

