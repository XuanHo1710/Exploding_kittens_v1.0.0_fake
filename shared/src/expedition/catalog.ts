function makeHeroSkills(
  heroId: string,
  el: ElementType,
  role: HeroRole,
  defs: [
    { id: string; name: string; sum: string; hits: number; pwr: number; brk: number },
    { id: string; name: string; sum: string; ap: number; scope: CombatSkillDefinition['targetScope']; hits: number; pwr: number; brk: number; canBrk?: boolean; heal?: number; shield?: number; apAlly?: number; spd?: number; vuln?: number; beam?: 'slash' | 'ray' | 'meteor' | 'wave' | 'sigil' },
    { id: string; name: string; sum: string; ap: number; scope: CombatSkillDefinition['targetScope']; hits: number; pwr: number; brk: number; canBrk?: boolean; heal?: number; shield?: number; apAlly?: number; spd?: number; vuln?: number; beam?: 'slash' | 'ray' | 'meteor' | 'wave' | 'sigil' },
    { id: string; name: string; sum: string; ap: number; scope: CombatSkillDefinition['targetScope']; hits: number; pwr: number; brk: number; canBrk?: boolean; heal?: number; shield?: number; apAlly?: number; spd?: number; vuln?: number; beam?: 'slash' | 'ray' | 'meteor' | 'wave' | 'sigil' },
    { id: string; name: string; sum: string },
  ],
): [CombatSkillDefinition, CombatSkillDefinition, CombatSkillDefinition, CombatSkillDefinition, CombatSkillDefinition] {
  const [b, a1, a2, u, p] = defs;
  const mkHits = (n: number, pwr: number, brk: number) =>
    Array.from({ length: n }, (_, idx) => ({
      powerMult: +(pwr / n).toFixed(2),
      breakDamage: Math.round(brk / n),
      timedHitOffsetMs: 260 + idx * 220,
    }));

  return [
    {
      skillId: b.id,
      heroId,
      slotKind: 'basic',
      nameVi: b.name,
      summaryVi: b.sum.replace(' (+3 AP nếu chuẩn nhịp)', '').replace('+2 AP', '+1 AP'),
      element: el,
      apCost: 0,
      apGain: 1,
      targetScope: 'single_enemy',
      hits: mkHits(b.hits, b.pwr, b.brk),
      canTriggerBreak: role === 'Breaker',
      vfxSpec: { castId: `${b.id}_cast`, effectId: `${b.id}_fx`, beamStyle: 'slash' },
    },
    {
      skillId: a1.id,
      heroId,
      slotKind: 'active',
      nameVi: a1.name,
      summaryVi: a1.sum,
      element: el,
      apCost: a1.ap,
      apGain: 0,
      targetScope: a1.scope,
      hits: a1.pwr > 0 ? mkHits(a1.hits, a1.pwr, a1.brk) : [{ powerMult: 0, breakDamage: 0, timedHitOffsetMs: 300 }],
      canTriggerBreak: Boolean(a1.canBrk || role === 'Breaker'),
      healRatio: a1.heal,
      shieldRatio: a1.shield,
      apGrantAlly: a1.apAlly,
      speedBuffTurns: a1.spd,
      vulnDebuffTurns: a1.vuln,
      vfxSpec: { castId: `${a1.id}_cast`, effectId: `${a1.id}_fx`, beamStyle: a1.beam ?? 'slash' },
    },
    {
      skillId: a2.id,
      heroId,
      slotKind: 'active',
      nameVi: a2.name,
      summaryVi: a2.sum,
      element: el,
      apCost: a2.ap,
      apGain: 0,
      targetScope: a2.scope,
      hits: a2.pwr > 0 ? mkHits(a2.hits, a2.pwr, a2.brk) : [{ powerMult: 0, breakDamage: 0, timedHitOffsetMs: 300 }],
      canTriggerBreak: Boolean(a2.canBrk ?? true),
      healRatio: a2.heal,
      shieldRatio: a2.shield,
      apGrantAlly: a2.apAlly,
      speedBuffTurns: a2.spd,
      vulnDebuffTurns: a2.vuln,
      vfxSpec: { castId: `${a2.id}_cast`, effectId: `${a2.id}_fx`, beamStyle: a2.beam ?? 'wave' },
    },
    {
      skillId: u.id,
      heroId,
      slotKind: 'ultimate',
      nameVi: u.name,
      summaryVi: u.sum,
      element: el,
      apCost: u.ap,
      apGain: 0,
      targetScope: u.scope,
      hits: u.pwr > 0 ? mkHits(u.hits, u.pwr, u.brk) : [{ powerMult: 0, breakDamage: 0, timedHitOffsetMs: 340 }],
      canTriggerBreak: true,
      healRatio: u.heal,
      shieldRatio: u.shield,
      apGrantAlly: u.apAlly,
      speedBuffTurns: u.spd,
      vulnDebuffTurns: u.vuln,
      vfxSpec: { castId: `${u.id}_cast`, effectId: `${u.id}_fx`, beamStyle: u.beam ?? 'meteor' },
    },
    {
      skillId: p.id,
      heroId,
      slotKind: 'passive',
      nameVi: p.name,
      summaryVi: p.sum,
      element: el,
      apCost: 0,
      apGain: 0,
      targetScope: 'self',
      hits: [],
      canTriggerBreak: false,
      vfxSpec: { castId: `${p.id}_cast`, effectId: `${p.id}_fx`, beamStyle: 'sigil' },
    },
  ];
}

