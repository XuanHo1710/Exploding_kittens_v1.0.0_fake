export function heroCombatSkillIds(hero: HeroDefinition): string[] {
  return [...hero.skillIds.slice(1, 4), ...EXTRA_SKILLS.filter((skill) => skill.heroId === hero.heroId).map((skill) => skill.skillId)];
}

export function configuredSkillIds(hero: HeroDefinition, owned: HeroInstance, learned: readonly string[]): string[] {
  const allowed = heroCombatSkillIds(hero).filter((id) => learned.includes(id));
  return [...new Set(owned.equippedSkillIds ?? allowed)].filter((id) => allowed.includes(id)).slice(0, 6);
}

