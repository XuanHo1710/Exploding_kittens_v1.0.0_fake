# ---------------------------------------------------------------- Vietnamese
import unicodedata

G["Đ"] = [".###..", ".#..#.", ".#...#", "####.#", ".#...#", ".#..#.", ".###.."]
G["đ"] = ["...#.", "..###", ".###.", "#..#.", "#..#.", "#..#.", ".###."]
MARKS = {   # combining mark -> (rows, kind)
    "̂": [".#.", "#.#"],            # circumflex
    "̆": ["#..#", ".##."],          # breve
    "́": ["..#", ".#."],            # acute (sắc)
    "̀": ["#..", ".#."],            # grave (huyền)
    "̉": ["##", ".#"],              # hook above (hỏi)
    "̃": [".#.#", "#.#."],          # tilde (ngã)
}
SHAPE_MARKS = {"̂", "̆"}
TONE = {"́", "̀", "̉", "̃"}
HORN, DOT = "̛", "̣"


def _clusters(text):
    out = []
    for ch in unicodedata.normalize("NFD", text):
        if unicodedata.combining(ch) and out:
            out[-1][1].append(ch)
        else:
            out.append([ch, []])
    return out


def _glyph(base, marks):
    """-> (set of (x, y) pixels, width); y may be negative (marks above the cap line)."""
    rows = G[base]
    pix = {(i, j) for j, r in enumerate(rows) for i, c in enumerate(r) if c == "#"}
    w = len(rows[0])
    low = base.islower()
    top = 2 if low and base not in "bdfhklt" else 0
    if base == "i" and (set(marks) & (SHAPE_MARKS | TONE)):
        pix = {(x, y) for x, y in pix if y != 0}
    if HORN in marks:
        pix |= {(w, top), (w, top - 1)}
        w += 1
    stack = [m for m in marks if m in SHAPE_MARKS] + [m for m in marks if m in TONE]
    mw = max([len(MARKS[m][0]) for m in stack] + [w])
    if mw > w:
        dx = (mw - w) // 2
        pix = {(x + dx, y) for x, y in pix}
        w = mw
    cur = top - 1
    for m in stack:
        mr = MARKS[m]
        x0 = (w - len(mr[0]) + 1) // 2
        y0 = cur - len(mr)
        pix |= {(x0 + i, y0 + j) for j, r in enumerate(mr) for i, c in enumerate(r) if c == "#"}
        cur = y0
    if DOT in marks:
        pix.add((w // 2, 8 if base not in "gjpqy" else 9))
    return pix, w


def vwidth(text):
    w = 0
    for base, marks in _clusters(text):
        w += SPACE + 1 if base == " " else _glyph(base, marks)[1] + 1
    return w


def vdraw(img, x, y, text, ink=(72, 72, 88), shadow=(208, 208, 216)):
    px = img.load()
    for layer, col in ((1, shadow), (0, ink)):
        cx = x
        for base, marks in _clusters(text):
            if base == " ":
                cx += SPACE + 1
                continue
            pix, w = _glyph(base, marks)
            for i, j in pix:
                pts = [(cx + i + 1, y + j), (cx + i, y + j + 1), (cx + i + 1, y + j + 1)] if layer else [(cx + i, y + j)]
                for X, Y in pts:
                    if 0 <= X < img.width and 0 <= Y < img.height and (not layer or px[X, Y][:3] != ink):
                        px[X, Y] = col + (255,)
            cx += w + 1
    return cx


draw, width = vdraw, vwidth

